import type { ReactNode } from 'react';

import type { IconName } from './icon-names';

const GRID = 12;
const CELL = 24 / GRID;

/**
 * Cada icono se dibuja sobre una reticula de 12x12 descrita con texto: `#`
 * pinta y `.` deja vacio. Trabajar sobre la reticula mantiene las siluetas
 * reconocibles y hace evidente en el codigo que forma tiene cada icono.
 *
 * Las celdas contiguas de una fila se agrupan en un solo rectangulo para no
 * emitir un nodo por pixel.
 */
function pixels(rows: readonly string[]): ReactNode {
  const shapes: ReactNode[] = [];

  rows.forEach((row, rowIndex) => {
    let runStart: number | null = null;

    for (let column = 0; column <= GRID; column += 1) {
      const isFilled = row[column] === '#';

      if (isFilled && runStart === null) {
        runStart = column;
      }

      if (!isFilled && runStart !== null) {
        shapes.push(
          <rect
            key={`${rowIndex}-${runStart}`}
            x={runStart * CELL}
            y={rowIndex * CELL}
            width={(column - runStart) * CELL}
            height={CELL}
          />,
        );
        runStart = null;
      }
    }
  });

  return <>{shapes}</>;
}

